# Which way each test-set word leans: log((count in positive + 1) /
# (count in negative + 1)) over words that appear at least 4 times. Used to
# highlight the sample reviews above.
counts = class_word_counts(test_texts, test_y)
words = [w for w in set(counts[0]) | set(counts[1]) if counts[0][w] + counts[1][w] >= 4]
lean = {w: np.log((counts[1][w] + 1) / (counts[0][w] + 1)) for w in words}
lean_max = max(abs(v) for v in lean.values())

def mark_lean(match):
    token = match.group(0).lower()
    if token in lean and lean[token] != 0:
        alpha = 0.2 + 0.5 * abs(lean[token]) / lean_max
        rgb = "44,160,44" if lean[token] > 0 else "214,39,40"
        return (f"<span style='background: rgba({rgb},{alpha:.2f}); "
                f"border-radius:3px; padding:0 2px'>{match.group(0)}</span>")
    return match.group(0)

