CLOUD_PNGS = {1: HERE / "test_cloud_positive.png", 0: HERE / "test_cloud_negative.png"}


def class_word_counts(texts, labels):
    """{label: Counter of words} with stopwords and generator scaffolding removed."""
    scaffold = " ".join(TEMPLATES + HEDGES + CONNECT_POS + CONNECT_MIX + PRODUCTS)
    skip = set(ENGLISH_STOP_WORDS) | set(re.findall(r"[a-z']+", scaffold.lower()))
    return {c: Counter(w for t, y in zip(texts, labels) if y == c
                       for w in re.findall(r"[a-z']+", t.lower())
                       if w not in skip and len(w) > 2)
            for c in (0, 1)}


def load_word_clouds(texts, labels):
    """Return {label: png path}; render the PNGs first if they do not exist."""
    if all(p.exists() for p in CLOUD_PNGS.values()):
        return CLOUD_PNGS
    from wordcloud import WordCloud
    counts = class_word_counts(texts, labels)
    for c, path in CLOUD_PNGS.items():
        mine, other = counts[c], counts[1 - c]
        weights = {w: n * (n / (n + other[w])) ** 2 for w, n in mine.items() if n >= 2}
        WordCloud(width=800, height=450, background_color="white",
                  colormap="Greens" if c == 1 else "Reds", max_words=80,
                  random_state=0).generate_from_frequencies(weights).to_file(path)
    return CLOUD_PNGS

