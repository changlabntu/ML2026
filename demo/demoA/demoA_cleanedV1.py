CONNECT_POS = ["and", "plus", "and honestly", "and on top of that"]
CONNECT_MIX = ["but", "although", "even if", "that said,", "though",
               "on the other hand"]

# {Main} is the main clause with its first letter capitalized.
TEMPLATES = [
    "{hedge} this {product}: {main}, {conn} {other}.",
    "{hedge} {main} with this {product}, {conn} {other}.",
    "Bought this {product} a while back. {Main}, {conn} {other}.",
    "{Main}, {conn} {other}. That is my experience with this {product}.",
    "{hedge} {main}, {conn} {other}. Still deciding about the {product}.",
    "Review of my {product}: {main}; {conn} {other}.",
]


def _cap(s):
    return s[0].upper() + s[1:]


def _compose(rng, product, main, other, connector):
    text = rng.choice(TEMPLATES).format(
        hedge=rng.choice(HEDGES), product=product, main=main,
        Main=_cap(main), conn=connector, other=other)
    return _cap(" ".join(text.split()))


def make_review(rng, kind, concession):
    """kind: 'pos', 'neg', or 'ambig'. Returns (text, label)."""
    product = rng.choice(PRODUCTS)
    if kind in ("pos", "neg"):
        same, opposite = ((POS_CLAUSES, NEG_CLAUSES) if kind == "pos"
                          else (NEG_CLAUSES, POS_CLAUSES))
        main = rng.choice(same)
        r = rng.random()
        if r < concession:
            text = _compose(rng, product, main, rng.choice(opposite), rng.choice(CONNECT_MIX))
        elif r < concession + 0.4 * (1 - concession):
            text = _compose(rng, product, main, rng.choice(NEUTRAL_CLAUSES), rng.choice(CONNECT_MIX))
        else:
            text = _compose(rng, product, main, rng.choice(same), rng.choice(CONNECT_POS))
        return text, int(kind == "pos")
    # ambiguous: neutral core, one random-sentiment aside, random label
    main = rng.choice(NEUTRAL_CLAUSES)
    aside = rng.choice(POS_CLAUSES) if rng.random() < 0.5 else rng.choice(NEG_CLAUSES)
    if rng.random() < 0.5:
        text = _compose(rng, product, main, aside, rng.choice(CONNECT_MIX))
    else:
        text = _compose(rng, product, aside, rng.choice(NEUTRAL_CLAUSES), rng.choice(CONNECT_MIX))
    return text, int(rng.random() < 0.5)


@st.cache_data
def make_split(n_pos, n_neg, n_ambig, concession, seed):
    """Generate n_pos clear-positive, n_neg clear-negative and n_ambig
    ambiguous reviews, shuffled. Returns (texts, labels, kinds) where kinds
    is an array of 'clear' / 'ambiguous' — the app uses it to show the ceiling."""
    rng = np.random.default_rng(seed)
    plan = ["pos"] * n_pos + ["neg"] * n_neg + ["ambig"] * n_ambig
    rows = [make_review(rng, k, concession) + (k,) for k in plan]
    rng.shuffle(rows)
    texts = [t for t, _, _ in rows]
    labels = np.array([l for _, l, _ in rows])
    kinds = np.array(["ambiguous" if k == "ambig" else "clear" for _, _, k in rows])
    return texts, labels, kinds


